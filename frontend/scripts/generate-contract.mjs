// Copies the JSON examples in contract/examples into an Elm module, because an
// Elm test cannot read a file. The Elm half of the contract tests decodes these
// strings; the Kotlin half reads the files directly. CI runs this script and
// fails if the committed module differs from what it writes.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const examplesDirectory = join(here, "..", "..", "contract", "examples");
const target = join(here, "..", "tests", "Contract", "Examples.elm");

// claim.awaiting-review.json -> claimAwaitingReview
const elmName = (fileName) =>
  fileName
    .replace(/\.json$/, "")
    .split(/[.-]/)
    .map((word, index) => (index === 0 ? word : word[0].toUpperCase() + word.slice(1)))
    .join("");

// The JSON goes into a triple-quoted Elm string, where only a backslash needs escaping.
const elmString = (json) => `"""${json.replaceAll("\\", "\\\\")}"""`;

const examples = readdirSync(examplesDirectory)
  .filter((fileName) => fileName.endsWith(".json"))
  .sort()
  .map((fileName) => ({
    fileName,
    name: elmName(fileName),
    json: JSON.stringify(JSON.parse(readFileSync(join(examplesDirectory, fileName), "utf8"))),
  }));

const declarations = examples.map(
  ({ fileName, name, json }) =>
    `{-| contract/examples/${fileName}\n-}\n${name} : String\n${name} =\n    ${elmString(json)}`,
);

const source = `module Contract.Examples exposing
    ( ${examples.map(({ name }) => name).join("\n    , ")}
    )

{-| The JSON examples in \`contract/examples\`, as strings.

Generated by \`scripts/generate-contract.mjs\`. Do not edit: change the JSON
files and run \`npm run contract\`.

-}


${declarations.join("\n\n\n")}
`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, source);
console.log(`Wrote ${examples.length} examples to tests/Contract/Examples.elm`);
